using System.Text;
using Aspire.Hosting.ApplicationModel;
using Aspire.Hosting.Pipelines;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace CookieJar.AppHost.Publishing;

/// <summary>
/// Minimal resource representing the Kamal deployment target.
/// Configure this in AppHost.cs to control how deploy.yml is generated.
/// </summary>
public sealed class KamalDeploymentResource(string name) : Resource(name)
{
    /// <summary>
    /// Kamal service name — used as the deploy.yml service key, image prefix, and accessory name prefix.
    /// Defaults to the resource name when not set.
    /// </summary>
    public string? ServiceName { get; init; }

    /// <summary>
    /// Target build architecture. Kamal always requires this even when using --skip-push.
    /// Typical values: "amd64" (Linux servers), "arm64" (Apple Silicon, Raspberry Pi).
    /// </summary>
    public string Architecture { get; init; } = "amd64";

    /// <summary>
    /// Environment variable names injected from .kamal/secrets into the app container.
    /// Aspire connection strings (DB, MQ) are added automatically; list only app-specific secrets here.
    /// </summary>
    public IReadOnlyList<string> ExtraSecretEnvVars { get; init; } = [];
}

/// <summary>
/// Aspire pipeline step that generates Kamal 2.x deployment artifacts:
///   config/deploy.yml  — deployment template with ${VAR} placeholders
///   .kamal/secrets.example — example secrets file with derived defaults
///
/// Register in AppHost.cs:
///   builder.AddResource(new KamalDeploymentResource("kamal") { ServiceName = "myapp", Architecture = "arm64" })
///          .WithPipelineStepFactory(KamalPipelineStep.Create);
///
/// Then run:
///   aspire publish --output-path ./deploy/output/kamal
///   cp deploy/output/kamal/.kamal/secrets.example deploy/output/kamal/.kamal/secrets
///   # fill in secrets, then:
///   ./deploy/kamal/3-deploy.sh all
/// </summary>
public static class KamalPipelineStep
{
    public static PipelineStep Create(PipelineStepFactoryContext factoryCtx)
    {
        var model = factoryCtx.PipelineContext.Model;

        var step = new PipelineStep
        {
            Name = "generate-kamal-config",
            Description = "Generate Kamal deployment artifacts (config/deploy.yml + .kamal/secrets.example)",
            RequiredBySteps = ["publish"],
            Action = stepCtx => GenerateAsync(stepCtx, model)
        };

        return step;
    }

    private static async Task GenerateAsync(PipelineStepContext ctx, DistributedApplicationModel model)
    {
        var outputService = ctx.Services.GetRequiredService<IPipelineOutputService>();
        var outputPath = outputService.GetOutputDirectory();
        var configPath = Path.Combine(outputPath, "config");
        var kamalPath = Path.Combine(outputPath, ".kamal");

        Directory.CreateDirectory(configPath);
        Directory.CreateDirectory(kamalPath);

        var kamal = model.Resources.OfType<KamalDeploymentResource>().First();
        var project = FindMainProject(model);

        await File.WriteAllTextAsync(
            Path.Combine(configPath, "deploy.yml"),
            BuildDeployYml(model, kamal, project),
            ctx.CancellationToken);

        await File.WriteAllTextAsync(
            Path.Combine(kamalPath, "secrets.example"),
            BuildSecretsExample(model, kamal, project),
            ctx.CancellationToken);

        ctx.Logger.LogInformation("Kamal artifacts written to {Path}", outputPath);
        ctx.PipelineContext.Summary.Add("📦 Kamal config", outputPath);
    }

    // The "main project" is the ProjectResource with an HTTP probe annotation — that's the one Kamal deploys.
    private static ProjectResource? FindMainProject(DistributedApplicationModel model) =>
        model.Resources.OfType<ProjectResource>()
            .FirstOrDefault(r => r.Annotations.OfType<EndpointProbeAnnotation>().Any())
        ?? model.Resources.OfType<ProjectResource>().FirstOrDefault();

    private static string BuildDeployYml(
        DistributedApplicationModel model,
        KamalDeploymentResource kamal,
        ProjectResource? project)
    {
        var serviceName = kamal.ServiceName ?? kamal.Name;
        var healthCheckPath = project?.Annotations
            .OfType<EndpointProbeAnnotation>().FirstOrDefault()?.Path ?? "/health";

        var sb = new StringBuilder();

        sb.AppendLine("# Generated by Aspire KamalPipelineStep");
        sb.AppendLine("# Docs: https://kamal-deploy.org/docs/configuration/");
        sb.AppendLine("# Update all TODO markers before deploying.");
        sb.AppendLine();
        sb.AppendLine($"service: {serviceName}");
        sb.AppendLine($"image: {serviceName}  # registry prefix comes from registry.server below");
        sb.AppendLine();
        sb.AppendLine("servers:");
        sb.AppendLine("  web:");
        sb.AppendLine("    - ${SERVER_IP}  # TODO: set SERVER_IP in .kamal/secrets");
        sb.AppendLine();
        sb.AppendLine("proxy:");
        sb.AppendLine("  ssl: false  # set to true and add host: for production");
        sb.AppendLine("  app_port: 8080");
        sb.AppendLine("  healthcheck:");
        sb.AppendLine($"    path: {healthCheckPath}");
        sb.AppendLine();
        sb.AppendLine("ssh:");
        sb.AppendLine("  user: ${SSH_USER}  # ubuntu for Multipass, root for most cloud VMs");
        sb.AppendLine("  keys:");
        sb.AppendLine("    - ${SSH_KEY}");
        sb.AppendLine();
        sb.AppendLine("registry:");
        sb.AppendLine("  server: ${REGISTRY_HOST}");
        sb.AppendLine("  username:");
        sb.AppendLine("    - REGISTRY_USERNAME");
        sb.AppendLine("  password:");
        sb.AppendLine("    - REGISTRY_PASSWORD");
        sb.AppendLine();
        sb.AppendLine("builder:");
        sb.AppendLine($"  arch: {kamal.Architecture}");
        sb.AppendLine();
        sb.AppendLine("env:");
        sb.AppendLine("  clear:");
        sb.AppendLine("    ASPNETCORE_ENVIRONMENT: Production");
        sb.AppendLine("    ASPNETCORE_HTTP_PORTS: \"8080\"");
        sb.AppendLine("  secret:");

        foreach (var key in DeriveSecretKeys(model, kamal))
            sb.AppendLine($"    - {key}");

        sb.AppendLine();
        sb.AppendLine("accessories:");

        var accessories = BuildAccessories(model, serviceName);
        if (string.IsNullOrWhiteSpace(accessories))
            sb.AppendLine("  # No container resources detected in the AppHost model");
        else
            sb.Append(accessories);

        return sb.ToString();
    }

    private static IEnumerable<string> DeriveSecretKeys(DistributedApplicationModel model, KamalDeploymentResource kamal)
    {
        foreach (var resource in model.Resources)
        {
            if (resource is PostgresDatabaseResource db)
                yield return $"ConnectionStrings__{db.Name}";

            if (resource is RabbitMQServerResource mq)
                yield return $"ConnectionStrings__{mq.Name}";
        }

        foreach (var key in kamal.ExtraSecretEnvVars)
            yield return key;
    }

    private static string BuildAccessories(DistributedApplicationModel model, string serviceName)
    {
        var sb = new StringBuilder();

        foreach (var pg in model.Resources.OfType<PostgresServerResource>())
        {
            var db = model.Resources.OfType<PostgresDatabaseResource>()
                .FirstOrDefault(d => d.Parent == pg);
            var dbName = db?.Name ?? pg.Name;
            var pgUser = GetUserName(pg.UserNameParameter, "postgres");
            var image = GetContainerImage(pg, "postgres:16-alpine");

            sb.AppendLine("  db:");
            sb.AppendLine($"    image: {image}");
            sb.AppendLine("    host: ${SERVER_IP}");
            sb.AppendLine("    port: 5432");
            sb.AppendLine("    env:");
            sb.AppendLine("      clear:");
            sb.AppendLine($"        POSTGRES_DB: {dbName}");
            sb.AppendLine($"        POSTGRES_USER: {pgUser}");
            sb.AppendLine("      secret:");
            sb.AppendLine("        - POSTGRES_PASSWORD");
            sb.AppendLine("    directories:");
            sb.AppendLine("      - data:/var/lib/postgresql");
            sb.AppendLine("        # postgres 18+ expects /var/lib/postgresql (not /data) as the base mount");
        }

        foreach (var mq in model.Resources.OfType<RabbitMQServerResource>())
        {
            var mqUser = GetUserName(mq.UserNameParameter, "guest");
            var image = GetContainerImage(mq, "rabbitmq:3-management-alpine");

            sb.AppendLine("  mq:");
            sb.AppendLine($"    image: {image}");
            sb.AppendLine("    host: ${SERVER_IP}");
            sb.AppendLine("    port: 5672");
            sb.AppendLine("    env:");
            sb.AppendLine("      clear:");
            sb.AppendLine($"        RABBITMQ_DEFAULT_USER: {mqUser}");
            sb.AppendLine("      secret:");
            sb.AppendLine("        - RABBITMQ_DEFAULT_PASS");
            sb.AppendLine("    directories:");
            sb.AppendLine("      - data:/var/lib/rabbitmq/mnesia");
        }

        // Dockerfile-built resources (e.g., React frontend, Python sensor).
        foreach (var container in model.Resources.OfType<ContainerResource>()
            .Where(r => r.Annotations.OfType<DockerfileBuildAnnotation>().Any()))
        {
            var endpoint = container.Annotations.OfType<EndpointAnnotation>().FirstOrDefault();

            sb.AppendLine($"  {container.Name}:");
            sb.AppendLine($"    image: ${{REGISTRY_HOST}}/{serviceName}-{container.Name}:latest");
            sb.AppendLine("    host: ${SERVER_IP}");

            if (endpoint is not null)
            {
                // HTTP-serving container — expose on host and route API calls via kamal-proxy
                var portMapping = endpoint.Port is not null
                    ? $"\"{endpoint.Port}:{endpoint.TargetPort}\""
                    : (endpoint.TargetPort ?? 80).ToString();
                sb.AppendLine($"    port: {portMapping}");
                sb.AppendLine("    env:");
                sb.AppendLine("      clear:");
                // SERVER_URL uses kamal-proxy container name so nginx reaches the main service
                // directly through the Docker network without going out to the host.
                sb.AppendLine("        SERVER_URL: http://kamal-proxy");
            }
            else
            {
                // Worker container — no host port, inject any connection strings it may need
                var workerSecrets = DeriveSecretKeys(model, new KamalDeploymentResource(container.Name)).ToList();
                if (workerSecrets.Count > 0)
                {
                    sb.AppendLine("    env:");
                    sb.AppendLine("      secret:");
                    foreach (var key in workerSecrets)
                        sb.AppendLine($"        - {key}");
                }
            }
        }

        return sb.ToString();
    }

    private static string GetUserName(ParameterResource? param, string defaultUser)
    {
        if (param is null) return defaultUser;
#pragma warning disable CS0618 // Value is obsolete for production use; acceptable for code generation
        return param.Value;
#pragma warning restore CS0618
    }

    private static string GetContainerImage(IResource resource, string fallback)
    {
        var ann = resource.Annotations.OfType<ContainerImageAnnotation>().FirstOrDefault();
        if (ann is null) return fallback;
        var registry = string.IsNullOrEmpty(ann.Registry) ? "" : $"{ann.Registry}/";
        var tag = string.IsNullOrEmpty(ann.Tag) ? "latest" : ann.Tag;
        return $"{registry}{ann.Image}:{tag}";
    }

    private static string BuildSecretsExample(
        DistributedApplicationModel model,
        KamalDeploymentResource kamal,
        ProjectResource? project)
    {
        var serviceName = kamal.ServiceName ?? kamal.Name;

        var pg = model.Resources.OfType<PostgresServerResource>().FirstOrDefault();
        var db = model.Resources.OfType<PostgresDatabaseResource>().FirstOrDefault();
        var mq = model.Resources.OfType<RabbitMQServerResource>().FirstOrDefault();

        var pgUser = GetUserName(pg?.UserNameParameter, "postgres");
        var mqUser = GetUserName(mq?.UserNameParameter, "guest");
        var dbName = db?.Name ?? pg?.Name ?? "db";
        var mqName = mq?.Name ?? "messaging";

        // Kamal accessory container names follow the pattern {service}-{accessory_name}
        var pgHost = $"{serviceName}-db";
        var mqHost = $"{serviceName}-mq";

        var sb = new StringBuilder();
        sb.AppendLine("# .kamal/secrets — copy to .kamal/secrets and fill in values.");
        sb.AppendLine("# IMPORTANT: Add .kamal/secrets to .gitignore!");
        sb.AppendLine("# Docs: https://kamal-deploy.org/docs/configuration/secrets/");
        sb.AppendLine();
        sb.AppendLine("# Target server — IP of the VM/bare-metal host Kamal deploys to");
        sb.AppendLine("SERVER_IP=CHANGEME");
        sb.AppendLine();
        sb.AppendLine("# SSH user and key used by Kamal to connect to the server");
        sb.AppendLine("# Multipass default user is 'ubuntu'; most cloud VMs use 'root'");
        sb.AppendLine("SSH_USER=ubuntu");
        sb.AppendLine("SSH_KEY=~/.ssh/id_ed25519");
        sb.AppendLine();
        sb.AppendLine("# Container registry — e.g. ghcr.io or a local registry reachable from the server");
        sb.AppendLine("REGISTRY_HOST=CHANGEME");
        sb.AppendLine("REGISTRY_USERNAME=unused       # leave as-is for a local unauthenticated registry");
        sb.AppendLine("REGISTRY_PASSWORD=unused");
        sb.AppendLine();
        sb.AppendLine($"# Aspire-style connection strings injected into the app container.");
        sb.AppendLine($"# Accessories run on the 'kamal' Docker network — use container names as hosts:");
        sb.AppendLine($"#   {pgHost}  (postgres)");
        sb.AppendLine($"#   {mqHost}  (rabbitmq)");
        sb.AppendLine($"ConnectionStrings__{dbName}=Host={pgHost};Port=5432;Database={dbName};Username={pgUser};Password=CHANGEME");
        sb.AppendLine($"ConnectionStrings__{mqName}=amqp://{mqUser}:CHANGEME@{mqHost}:5672");

        foreach (var key in kamal.ExtraSecretEnvVars)
            sb.AppendLine($"{key}=CHANGEME");

        sb.AppendLine();
        sb.AppendLine("# Accessory service secrets");
        sb.AppendLine("POSTGRES_PASSWORD=CHANGEME");
        sb.AppendLine("RABBITMQ_DEFAULT_PASS=CHANGEME");
        return sb.ToString();
    }
}
